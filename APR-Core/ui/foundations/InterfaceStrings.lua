function APR:LocalizeUI(key, ...)
    local pair = labels[key]
    local text = rawget(L, "UI_" .. key) or (pair and pair[GetLocale() == "frFR" and 2 or 1]) or key
    if select("#", ...) > 0 then return string.format(text, ...) end
    return text
end
