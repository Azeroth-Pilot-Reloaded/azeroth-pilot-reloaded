local F = dofile('tests/lua/navigation_v2_taxi/fixture.lua')
local ns = F.Load()
local route=F.Route('flight','west','east',6,10)
local planner=assert(ns.LibAPRNavigationV2.New({complete=true,nodes={'west','east'},edges={}},F.Options({route},10)))
local result=F.Finish(planner:Plan({from='west',to='east'}))
local travel=assert(planner:StartTravel(result))
assert(travel:GetAction().kind=='approach')
travel:Observe({sequence=1,reliable=true,node='west',stopID='west',worldID=7,floorID=0,phaseID='shared',onTaxi=false})
assert(travel:GetAction().kind=='board_taxi')
local quote={confirmed=true,originID='west',destinationID='east',reachable=true,fareCopper=7}
assert(select(2,travel:BeginTaxi(quote,{money=10}))=='taxi_fare_changed')
assert(travel:GetAction().kind=='board_taxi' and travel:RemainingRequest().from=='west')
quote.fareCopper=6
assert(select(2,travel:BeginTaxi(quote,{}))=='resources_unknown')
local action=assert(travel:BeginTaxi(quote,{money=10}))
assert(action.kind=='awaiting_taxi' and action.attempt and not travel:RemainingRequest())
local o={sequence=2,reliable=true,node='east',stopID='east',worldID=7,floorID=0,phaseID='shared',onTaxi=false,
    attempt=action.attempt,taxiId='flight'}
assert(travel:Observe(o).kind=='awaiting_taxi','Flight end/location alone cannot prove boarding')
o.sequence,o.onTaxi=3,true;assert(travel:Observe(o).kind=='riding_taxi')
o.sequence,o.onTaxi,o.floorID=4,false,1;assert(travel:Observe(o).kind=='riding_taxi')
o.sequence,o.floorID,o.loading=5,0,true;assert(travel:Observe(o).kind=='riding_taxi')
o.sequence,o.loading,o.attempt=6,false,{};assert(travel:Observe(o).kind=='riding_taxi')
o.sequence,o.attempt=7,action.attempt;assert(travel:Observe(o).kind=='complete')
assert(travel:RemainingRequest().from=='east')
-- Failure and deadlines are terminal, keep the objective, and never restart.
travel=assert(planner:StartTravel(result))
travel:Observe({sequence=1,reliable=true,node='west',stopID='west',worldID=7,floorID=0,phaseID='shared',onTaxi=false})
action=assert(travel:BeginTaxi(quote,{money=10}))
assert(travel:Observe({sequence=2,reliable=true,failed=true,attempt=action.attempt,taxiId='flight'}).reason=='taxi_failed')
assert(not travel:RemainingRequest())
assert(travel:Observe({sequence=3,reliable=true,node='east'}).kind=='failed')
travel=assert(planner:StartTravel(result))
travel:Observe({sequence=1,reliable=true,node='west',stopID='west',worldID=7,floorID=0,phaseID='shared',onTaxi=false})
assert(select(2,travel:BeginTaxi(quote,{money=5}))=='resources_insufficient')
assert(travel:BeginTaxi(quote,{money=6}))
planner.clock=function()return 400 end
assert(travel:Tick().reason=='transition_timeout' and not travel:RemainingRequest())
assert(travel:Tick().kind=='failed')
assert(travel:Cancel().kind=='cancelled')
assert(travel:Tick().kind=='cancelled')
