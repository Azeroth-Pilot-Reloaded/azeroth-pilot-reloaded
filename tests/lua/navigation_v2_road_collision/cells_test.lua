local H=assert(loadfile('tests/lua/navigation_v2_road_collision/support.lua'))()
local api=H.Load()
local base=H.Mask('plain',{'....','....','....','....'})
local source=H.Source(api,base)
local state=H.Query(source,{x=3.2,y=3.1},{x=3.8,y=3.9})
assert(state.status=='complete',state.reason)
assert(state.scope=='declared_collision_cells_2d' and state.mode=='walk')
assert(state.z==nil and state.floor==nil and state.phase==nil)
assert(H.Query(source,{x=3.5,y=3.5},{x=.5,y=.5}).status=='complete')
assert(H.Query(source,{x=3.5,y=3.5},{x=3.5,y=3.5}).status=='complete')
assert(H.Query(source,{x=3.5,y=3.5},{x=-.5,y=3.5}).reason=='outside_domain')

source=H.Source(api,H.Mask('obstacle',{'.#..','....','....','....'}))
state=H.Query(source,{x=3.5,y=3.5},{x=3.5,y=.5})
assert(state.status=='blocked' and state.reason=='blocked_cell')
source=H.Source(api,H.Mask('water',{'~~~~'}))
state=H.Query(source,{x=3.5,y=3.5},{x=3.5,y=.5})
assert(state.status=='blocked' and state.reason=='water_requires_swim')
assert(H.Query(source,{x=3.5,y=3.5},{x=3.5,y=.5},'swim').status=='complete')
source=H.Source(api,base)
assert(H.Query(source,{x=3.5,y=3.5},{x=3.5,y=3.2},'swim').reason=='land_requires_walk')
source=H.Source(api,H.Mask('ambiguous',{'?'}))
assert(H.Query(source,{x=3.5,y=3.5},{x=3.2,y=3.2}).reason=='unknown_floor')

-- Only declared identities constrain a 2D domain; never invent height/floor.
source=H.Source(api,base,{}, {identity={floor='upper',phase='visible'}})
state=H.Query(source,{x=3.5,y=3.5},{x=3.2,y=3.2})
assert(state.status=='unknown' and state.reason=='floor_unknown')
assert(H.Query(source,{x=3.5,y=3.5,floor='upper',phase='visible'},
    {x=3.2,y=3.2,floor='upper',phase='visible'}).status=='complete')
assert(H.Query(source,{x=3.5,y=3.5,floor='lower',phase='visible'},
    {x=3.2,y=3.2,floor='upper',phase='visible'}).reason=='floor_mismatch')
source=H.Source(api,base)
assert(H.Query(source,{worldID=1,x=3.5,y=3.5},{x=3.2,y=3.2}).reason=='world_mismatch')
assert(H.Query(source,{x=3.5,y=3.5,floor='a'},{x=3.2,y=3.2,floor='b'}).reason=='floor_mismatch')
assert(H.Query(source,{x=3.5,y=3.5,floor='a'},{x=3.2,y=3.2}).reason=='floor_unknown')
print('Road collision: free points, obstacles, explicit modes and identities passed')
