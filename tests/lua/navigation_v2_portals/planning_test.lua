local F=dofile('tests/lua/navigation_v2_portals/fixture.lua')
local p=F.PortalPlanner()
local result=F.Finish(p:Plan({from='start',to='goal'}))
assert(result.status=='complete' and result.estimatedSeconds==13,'portal must beat the 27-second walk')
assert(result.segments[1].edgeId=='approach' and result.segments[2].kind=='portal')
assert(result.segments[2].edgeId=='portal:door' and result.segments[3].edgeId=='finish')
local via=F.Finish(p:Plan({from='start',to='goal',via={'gate'}}))
assert(via.estimatedSeconds==13)
assert(p:ObservePortals(F.Observation(2,false)))
assert(not p:IsCurrent(result))
local walk=F.Finish(p:Plan({from='start',to='goal'}))
assert(walk.estimatedSeconds==27 and walk.segments[2].edgeId=='walk')
local revision=p.revision
local changed,reason=p:ObservePortals(F.Observation(2))
assert(changed==false and reason=='stale_observation' and p.revision==revision)
assert(p:ObservePortals(F.Observation(3,true,'red'))==false) -- remains unavailable
assert(F.Finish(p:Plan({from='start',to='goal'})).estimatedSeconds==27)
local slow=F.PortalPlanner(30)
assert(F.Finish(slow:Plan({from='start',to='goal'})).estimatedSeconds==27)
assert(p:ObservePortals(F.Observation(4)))
assert(p:SetPortalCosts('door',{loadingSeconds=25}))
assert(F.Finish(p:Plan({from='start',to='goal'})).estimatedSeconds==27)
assert(p:SetPortalCosts('door',{loadingSeconds=0}))
assert(F.Finish(p:Plan({from='start',to='goal'})).estimatedSeconds==10)
