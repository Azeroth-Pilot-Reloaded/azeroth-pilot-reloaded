local F=dofile('tests/lua/navigation_v2_conditions/integration_fixture.lua')
for _,client in ipairs({'Standard','Camelot'})do
    local e=F.Host(client)
    local graph=F.Graph()
    graph.edges[1].requirements={phase='present',access={{key='gate',allowed=true}}}
    e:EnableConditions(graph,{conditionAccess={gate=true}})
    local r=e:FirstResult();assert(r.estimatedSeconds==3)
    e:StartWalk(r);assert(e:HasMarker())
    local revision=e.host.planner.revision
    e:Fire('UNIT_PHASE','target')
    assert(e.host.planner.revision==revision and e:HasMarker(),'Other unit phase is irrelevant')
    e:Fire('UNIT_PHASE','player')
    assert(e.host.conditionSource.identity.phase==nil and next(e.host.conditionSource.access)==nil)
    assert(not e:HasMarker() and not e.host.planner:IsCurrent(r))
    e.host:ResumeConditions();r=e:Finish()
    assert(r.estimatedSeconds==13,'Same map/readiness do not restore phase or access')
    assert(e.host:SetConditionIdentity({world=7,space='hall',floor='upper',phase='different'}))
    e.host:SetConditionAccess({gate=true});e.host:ResumeConditions();r=e:Finish()
    assert(r.estimatedSeconds==13,'Explicit different phase rejects the shortcut')
    e.host:SetConditionIdentity({world=7,space='hall',floor='upper',phase='present'})
    e.host:ResumeConditions();r=e:Finish();assert(r.estimatedSeconds==3)
    e:Fire('PLAYER_LEAVING_WORLD')
    assert(next(e.host.conditionSource.identity)==nil and next(e.host.conditionSource.access)==nil)
    e:Fire('PLAYER_ENTERING_WORLD')
    e.host:Plan({from='cave',to='goal'},e.context);r=e:Finish()
    assert(r.estimatedSeconds==13,'Entering world is not fresh phase/access proof')
    -- Neither a real subscription gap nor active replacement inherits old evidence.
    e.host:Disable();e:EnableConditions(graph,{conditionIdentity={},conditionAccess={}})
    r=e:FirstResult();assert(r.estimatedSeconds==13)
    e.host:SetConditionIdentity({phase='present'});e.host:SetConditionAccess({gate=true})
    e.host:ResumeConditions();assert(e:Finish().estimatedSeconds==3)
    e:EnableConditions(graph,{conditionIdentity={},conditionAccess={}})
    r=e:FirstResult();assert(r.estimatedSeconds==13)
    e:Cleanup()
end
-- Access-only declarations still revoke phase-scoped access on UNIT_PHASE.
local e=F.Host('Standard');local graph=F.Graph();graph.edges[1].requirements=F.Require('gate')
e:EnableConditions(graph,{conditionIdentity={},conditionAccess={gate=true}})
assert(e:FirstResult().estimatedSeconds==3)
e:Fire('UNIT_PHASE','player');e.host:ResumeConditions()
assert(e:Finish().estimatedSeconds==13)
e:Cleanup()
