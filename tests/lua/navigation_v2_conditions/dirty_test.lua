local ns={};assert(loadfile('APR-Core/libs/LibAPRNavigation-2.0/Conditions.lua'))('APR',ns)
local C=ns.NavigationV2Conditions
local t=C.New()
local a=assert(t:Track(assert(C.Compile({quests={{questID=201,completed=true}}}))))
local b=assert(t:Track(assert(C.Compile({quests={{questID=202,completed=true}},access={{key='closed',allowed=true}}}))))
assert(t:Observe({sequence=1,worldState='ready',quests={[201]=true,[202]=true},access={closed=false}}))
local token=t:GetToken()
assert(not t:MarkDirty({quests={[999]=true}}),'Unobserved quest is irrelevant')
assert(t:IsCurrent(token))
assert(t:MarkDirty({quests={[201]=true}}))
assert(not t:IsCurrent(token) and t:Get(a)=='unknown','Dirty evidence immediately retires jobs/results')
local dirtyToken=t:GetToken()
assert(not t:MarkDirty({quests={[201]=true}}),'Repeated event is coalesced')
assert(not t:MarkDirty({quests={[202]=true}}),'One invalidation per burst, including another dependency')
assert(t:GetToken().revision==dirtyToken.revision)
assert(not t:IsCurrent(dirtyToken),'Dirty tokens cannot authorize use')
local changed,why,recovered=t:Observe({sequence=2,worldState='ready',quests={[201]=true,[202]=false},access={closed=false}})
assert(not changed and why==nil and recovered,
    'Masked quest change does not change effective access')
assert(t:Get(a)=='available' and t:Get(b)=='unavailable')
assert(t:IsCurrent(t:GetToken()) and not t:IsCurrent(token))
local stable,_,again=t:Observe({sequence=3,worldState='ready',quests={[201]=true,[202]=false},access={closed=false}})
assert(not stable and not again,'A fresh identical capture can resume once; it never loops')
local fresh=t:GetToken()
assert(not t:Observe({sequence=4,worldState='ready',quests={[201]=true,[202]=nil},access={closed=false}}))
assert(t:IsCurrent(fresh),'A false conjunct masks unknown or changing unrelated facts')
assert(t:Observe({sequence=5,worldState='ready',quests={[201]=true},access={closed=true}}))
assert(t:Get(b)=='unknown','Unknown is distinct from denied access')
assert(t:Observe({sequence=6,worldState='ready',quests={[201]=true,[202]=true},access={closed=true}}))
assert(t:Get(b)=='available')
