local F=dofile('tests/lua/navigation_v2_conditions/integration_fixture.lua')
local p=F.Planner(F.Graph(),nil,{deferConditions=true})
local job=p:Plan({from='cave',to='goal',via={'town'}})
local r=F.Base.Finish(job,1)
assert(r.status=='observation_required')
assert(p:MarkConditionsDirty({quests={[711]=true}}))
local continued,why=job:ContinueConditions({sequence=1,worldState='ready',quests={[711]=true}})
assert(continued==nil and why=='stale_job','An invalidated suspended job cannot adopt later proof')
assert(job:Step(1).status=='stale' and job:GetResult().objective.via[1]=='town')
assert(p:ObserveConditions({sequence=1,worldState='ready',quests={[711]=true}})~=nil)
local fresh=F.Result(p,{from='cave',to='goal',via={'town'}})
assert(fresh.status=='complete' and fresh.estimatedSeconds==3 and not p:IsCurrent(r))
continued,why=job:ContinueConditions({sequence=2,worldState='ready',quests={[711]=true}})
assert(continued==nil and why=='conditions_not_requested')
