local H=dofile('tests/lua/navigation_v2_movement/host_fixture.lua')
local env,h=H.New()
local graph=H.Graph({'s','g'},{H.Edge('ride','s','g','mount',112)})
env:Enable(graph)
h:Plan({from='s',to='g'},env.context)
local result=env:Finish()
H.Path(result,{'ride'},13)
local scans=env.scans
env:Fire('PLAYER_LEAVING_WORLD')
assert(env.scans==scans,'loading invalidation must not scan the journal')
assert(not h.planner:IsCurrent(result),'loading event must invalidate the captured result')
assert(h:GetResult().status=='stale')
assert(select(2,h:StartTravel(result))=='stale_result','a pre-loading result cannot start execution')
h:Plan({from='s',to='g'},env.context)
assert(env:Finish().status=='unknown','transient APIs during loading cannot revalidate movement')
env:Fire('PLAYER_ENTERING_WORLD')
assert(h:GetTravelAction()==nil and #env.provider.creates==0)
h:Plan({from='s',to='g'},env.context)
H.Path(env:Finish(),{'ride'},13)
h:Disable()
