local F=dofile('tests/lua/navigation_v2_calibration/fixture.lua')
local c=F.New()
local handle,owner,attempt=F.Begin(c,100)
assert(c:Loading(handle,owner,attempt,true,102))
assert(c:Loading(handle,owner,attempt,false,105))
assert(c:Finish(handle,owner,attempt,113,true))
assert(c:Get('taxi/flight/ride')==10,'loading must not be charged twice')
assert(c:Get('taxi/flight/loading')==3)
assert(c:GetRevision()==1,'both components are one effective revision')
local h,o,a=F.Begin(c,200)
c:Loading(h,o,a,true,201)
c:Loading(h,o,a,false,209)
c:Cancel()
assert(not c:Finish(h,o,a,220,true))
assert(c:Get('taxi/flight/loading')==3,'interrupted observations cannot become samples')
assert(c:GetRevision()==1)
