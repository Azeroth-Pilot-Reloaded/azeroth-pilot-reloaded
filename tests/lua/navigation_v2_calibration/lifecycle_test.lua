local F=dofile('tests/lua/navigation_v2_calibration/fixture.lua')
local c=F.New()
local h,o,a=F.Begin(c,100)
local new,nowner,nattempt=F.Begin(c,200)
assert(not c:Finish(h,o,a,210,true),'old callback rejected')
assert(not c:Loading(new,o,a,true,210),'old execution ownership rejected')
assert(not c:Loading(new,o,nattempt,true,210),'owner alone distinguishes executions')
assert(not c:Loading(new,nowner,a,true,210),'attempt alone distinguishes segments within an execution')
assert(c:Finish(new,nowner,nattempt,220,true)==false,'unchanged default is no effective revision')
assert(c:GetStats().accepted==1 and c:GetRevision()==0)
for _,finish in ipairs({99,100,100.01,10000,math.huge,0/0}) do
    h,o,a=F.Begin(c,100)
    assert(not c:Finish(h,o,a,finish,true))
end
h,o,a=F.Begin(c,100)
assert(not c:Finish(h,o,a,nil,true))
h,o,a=F.Begin(c,100)
assert(not c:Finish(h,o,a,110,false))
h,o,a=F.Begin(c,100)
assert(not c:Loading(h,o,a,false,101),'unpaired exit invalidates all')
assert(not c:Finish(h,o,a,110,true))
h,o,a=F.Begin(c,100)
assert(c:Loading(h,o,a,true,101))
assert(not c:Loading(h,o,a,true,102),'unpaired entry invalidates all')
h,o,a=F.Begin(c,100)
assert(c:Loading(h,o,a,true,101))
assert(not c:Loading(h,o,a,false,100),'regressed intermediate clock invalidates all')
h,o,a=F.Begin(c,100)
assert(c:Loading(h,o,a,true,101))
assert(not c:Finish(h,o,a,110,true),'unterminated loading rejects ride and loading')
local loadingOnly=F.New()
o,a={},{}
h=assert(loadingOnly:Begin({loading='taxi/flight/loading'},o,a,100))
assert(loadingOnly:Loading(h,o,a,true,100))
assert(loadingOnly:Loading(h,o,a,false,105))
assert(loadingOnly:Finish(h,o,a,105,true),'loading-only journey may have no residual ride time')
assert(loadingOnly:Get('taxi/flight/loading')==5)
assert(loadingOnly:Get('taxi/flight/ride')==20)
