local F=dofile('tests/lua/navigation_v2_unlocks/fixture.lua')
local p=F.Planner()
local request={from='cave',to='goal',via={'town'}}
local journey=assert(F.Library.NewJourney(request))
local result=F.Result(p,request)
local travel=assert(p:StartTravel(result,nil,journey))
assert(travel:GetAction().node=='keeper')
local action=travel:Observe({sequence=1,reliable=true,loading=false,node='keeper'})
assert(action.kind=='unlock' and action.unlockId=='speak-keeper','Marker arrival waits for actual access proof')
assert(journey.objective.to=='goal' and journey.viaIndex==0 and journey.node=='keeper')
assert(journey:RemainingRequest().to=='keeper' and journey:OriginalRequest().via[1]=='town')
assert(not p:ResumeUnlock(journey),'Unchanged denial cannot resume the original request')
assert(p:ObserveConditions({sequence=2,worldState='ready',access={['garden-open']=false}})==false)
assert(not p:ResumeUnlock(journey),'A newer sequence alone is not positive proof')
assert(p:ObserveConditions({sequence=3,worldState='ready',access={['garden-open']=true}}))
local resumed=assert(p:ResumeUnlock(journey))
assert(resumed.objective.from=='keeper' and resumed.objective.to=='goal' and resumed.objective.via[1]=='town')
local r=F.Base.Finish(resumed,1)
assert(r.status=='complete' and not r.unlock and r.estimatedSeconds==4)
assert(travel:GetAction().kind=='cancelled','Old execution is invalid after new proof')
local final=assert(p:StartTravel(r,nil,journey))
assert(final:Observe({sequence=1,reliable=true,node='town'}).node=='goal')
assert(journey.viaIndex==1)
assert(final:Observe({sequence=2,reliable=true,node='goal'}).kind=='complete')
assert(journey.objective.from=='cave' and journey.objective.to=='goal')
