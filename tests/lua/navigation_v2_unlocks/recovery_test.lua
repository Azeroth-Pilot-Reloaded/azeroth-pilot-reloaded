local F=dofile('tests/lua/navigation_v2_unlocks/host_fixture.lua')
local e=F.Host('Standard',false)
local r=e:Result();e:Start(r)
local journey=e.host.journey
local previous=e.host.job
e.host:MarkConditionsDirty({access={['garden-open']=true}})
assert(not e.host.travel and journey.node=='cave')
e.host:SetConditionAccess({['garden-open']=false})
local resumed=e.host:ResumeConditions()
assert(resumed.status=='running' and e.host.job~=previous,'Fresh identical denial should recover the interrupted approach once')
assert(e.host.journey==journey and journey.unlock and journey:RemainingRequest().to=='keeper')
r=e:Finish();assert(r.unlock and r.travelObjective.from=='cave' and r.travelObjective.to=='keeper')
local job=e.host.job
assert(e.host:ResumeConditions().kind=='unlock' and e.host.job==job,'Unchanged proof cannot replan the same approach')
e:Start(r)
e.host:ObserveTravel({sequence=1,reliable=true,node='keeper'})
e.host:ObserveWorld(true)
assert(not journey.node)
e.host:ObserveWorld(false)
e.host:SetConditionAccess({['garden-open']=true})
local held=e.host:ResumeConditions()
assert(held.kind=='unlock' and held.reason=='location_unknown' and e.host.job==job)
assert(journey.unlock and journey.objective.to=='goal' and journey.viaIndex==0)
assert(not e:HasMarker() and e.quests==0)
e.host:Disable()
