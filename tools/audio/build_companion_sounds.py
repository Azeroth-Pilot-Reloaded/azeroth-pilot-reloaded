"""Explicit offline build of APR's CC0 warm bell palette. Requires FFmpeg.

Pass --source-dir with high.mp3, low.mp3 and doorbell.mp3 from the sources
documented in APR-Core/assets/sound/LICENSE-companion-sounds.txt. The accepted
V4 recipe keeps the recording in front and adds a pitch-matched lower body.
Nothing is downloaded and no addon runtime code is generated by this tool.
"""

import argparse
from array import array
import json
import math
from pathlib import Path
import re
import subprocess
import sys

RATE = 24000
BODY_SHARE = .25
# (Body frequency, strike time in the untrimmed public HQ preview.) The body
# sits one octave below each recording's measured main mode, with a quieter
# additional octave below it. These are audio editing choices, not runtime data.
SOURCE_NOTES = {
    "high": ((1333.34, .1885),),
    "low": ((475.28, .0530),),
    "doorbell": ((653.5, .0335), (592.5, .1895)),
}
SOURCE_FILTERS = (
    "highpass=f=55,"
    "equalizer=f=6113:t=q:w=1.5:g=-2.0,"
    "treble=g=-0.5:f=5000,"
    "acompressor=threshold=0.10:ratio=1.35:attack=0.2:release=35:knee=2:detection=peak:mix=0.6"
)


def run(ffmpeg: str, args: list[str], data: bytes | None = None, verbose=False):
    return subprocess.run([ffmpeg, "-hide_banner", *([] if verbose else ["-v", "error"]), *args],
                          input=data, capture_output=True, check=True)


def from_bytes(raw: bytes) -> list[float]:
    samples = array("f")
    samples.frombytes(raw)
    if sys.byteorder != "little":
        samples.byteswap()
    return list(samples)


def to_bytes(values: list[float]) -> bytes:
    samples = array("f", values)
    if sys.byteorder != "little":
        samples.byteswap()
    return samples.tobytes()


def raw_input() -> list[str]:
    return ["-f", "f32le", "-ar", str(RATE), "-ac", "1", "-i", "-"]


def energy(values: list[float]) -> float:
    return sum(v * v for v in values)


def validate(values: list[float], label: str):
    if not values or not all(math.isfinite(v) for v in values) or not energy(values):
        raise ValueError(f"Empty, silent or invalid audio: {label}")


def meter(ffmpeg: str, values: list[float]) -> dict:
    result = run(ffmpeg, [*raw_input(), "-af", "loudnorm=I=-22:TP=-3:LRA=11:print_format=json",
                          "-f", "null", "-"], to_bytes(values), verbose=True)
    match = re.search(rb'\{[^{}]+"input_i"[^{}]+\}', result.stderr)
    if not match:
        raise ValueError("FFmpeg did not return an audio loudness measurement")
    report = json.loads(match.group())
    if not math.isfinite(float(report["input_i"])):
        raise ValueError("Audio is too short or quiet for a loudness measurement")
    return report


def normalize(ffmpeg: str, values: list[float], target: float) -> list[float]:
    gain = 10 ** ((target - float(meter(ffmpeg, values)["input_i"])) / 20)
    result = [v * gain for v in values]
    validate(result, "normalized audio")
    return result


def prepare_source(ffmpeg: str, source: Path) -> tuple[list[float], float]:
    stereo = from_bytes(run(ffmpeg, ["-i", str(source), "-ac", "2", "-ar", str(RATE),
                                      "-f", "f32le", "-"]).stdout)
    if len(stereo) % 2:
        raise ValueError(f"Incomplete stereo frame: {source}")
    # This is the accepted V4 channel balance, not a room de-reverberation claim.
    values = [.90 * left + .10 * right for left, right in zip(stereo[::2], stereo[1::2])]
    validate(values, str(source))
    threshold = max(map(abs, values)) * 10 ** (-48 / 20)
    first = next(i for i, v in enumerate(values) if abs(v) > threshold)
    last = max(i for i, v in enumerate(values) if abs(v) > threshold)
    cut = max(0, first - int(.004 * RATE))
    values = values[cut:min(len(values), last + int(.025 * RATE))]
    gain = 10 ** (-25 / 20) / math.sqrt(energy(values) / len(values))
    values = [v * gain for v in values]
    values = from_bytes(run(ffmpeg, [*raw_input(), "-af", SOURCE_FILTERS, "-f", "f32le", "-"],
                            to_bytes(values)).stdout)
    for i in range(len(values)):
        tail = min(1., max(0., (i / RATE - .40) / .30))
        smooth = tail * tail * (3 - 2 * tail)
        values[i] *= 10 ** (-2 * smooth / 20)
        values[i] *= min(1., i / (.001 * RATE), (len(values) - 1 - i) / (.012 * RATE))
    return values, cut / RATE


def warm_source(ffmpeg: str, source_dir: Path, name: str) -> list[float]:
    source, trim_start = prepare_source(ffmpeg, source_dir / f"{name}.mp3")
    notes = [(frequency, max(0., start - trim_start)) for frequency, start in SOURCE_NOTES[name]]
    levels = []
    for _, start in notes:
        window = source[round((start + .012) * RATE):round((start + .085) * RATE)]
        validate(window, f"{name} strike")
        levels.append(math.sqrt(energy(window) / len(window)))
    maximum = max(levels)
    levels = [v / maximum for v in levels]
    body = [0.] * len(source)
    for (frequency, start), level in zip(notes, levels):
        offset, length = round(start * RATE), .34
        for i in range(min(round(length * RATE), len(body) - offset)):
            t = i / RATE
            attack = 1 - math.exp(-t / .0035)
            sample = (math.sin(math.tau * frequency * t) * math.exp(-t / .080)
                      + .38 * math.sin(math.tau * .5 * frequency * t) * math.exp(-t / .095))
            fade = min(1., max(0., (length - t) / .035))
            fade = fade * fade * (3 - 2 * fade)
            body[offset + i] += level * sample * attack * fade
    validate(body, f"{name} supporting body")
    gain = math.sqrt(energy(source) * BODY_SHARE / (1 - BODY_SHARE) / energy(body))
    values = [recording + support * gain for recording, support in zip(source, body)]
    # Equal starting loudness makes the event-specific offsets predictable.
    return normalize(ffmpeg, values, -22.)


def sequence(notes: list[list[float]], spacing: float = .180) -> list[float]:
    offset = round(spacing * RATE)
    result = [0.] * max(i * offset + len(note) for i, note in enumerate(notes))
    for i, note in enumerate(notes):
        for j, sample in enumerate(note):
            result[i * offset + j] += sample
    return result


def encode(ffmpeg: str, values: list[float], output: Path):
    validate(values, output.name)
    report = meter(ffmpeg, values)
    if float(report["input_tp"]) >= -3:
        raise ValueError(f"Insufficient peak headroom for {output.name}; review the offline mix")
    run(ffmpeg, ["-y", *raw_input(), "-c:a", "libvorbis", "-q:a", "6",
                 "-fflags", "+bitexact", "-map_metadata", "-1", str(output)], to_bytes(values))
    return {
        "duration_seconds": len(values) / RATE,
        "integrated_lufs": float(report["input_i"]),
        "true_peak_dbtp": float(report["input_tp"]),
        "bytes": output.stat().st_size,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ffmpeg", required=True)
    parser.add_argument("--source-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--preview-dir", type=Path, help="Optional lossless WAV masters and build report")
    args = parser.parse_args()
    high, low, doorbell = [warm_source(args.ffmpeg, args.source_dir, name)
                           for name in ("high", "low", "doorbell")]
    palette = {
        "match": (high, -26.),
        "received": (doorbell, -22.),
        "joined": (sequence([low, high]), -22.),
        "declined": (sequence([high, low]), -24.),
        "expired": (low, -29.),
        "error": (sequence([low, low], .105), -24.),
    }
    args.output_dir.mkdir(parents=True, exist_ok=True)
    if args.preview_dir:
        args.preview_dir.mkdir(parents=True, exist_ok=True)
    report = {}
    for event, (values, target) in palette.items():
        values = normalize(args.ffmpeg, values, target)
        output = args.output_dir / f"companion-{event}.ogg"
        report[event] = encode(args.ffmpeg, values, output)
        if args.preview_dir:
            run(args.ffmpeg, ["-y", *raw_input(), "-map_metadata", "-1", "-c:a", "pcm_s24le",
                             str(args.preview_dir / f"companion-{event}.wav")], to_bytes(values))
        print(f"{output.name}: {report[event]['duration_seconds']:.3f} s, "
              f"{report[event]['integrated_lufs']:.2f} LUFS, {output.stat().st_size} bytes")
    if args.preview_dir:
        (args.preview_dir / "build-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
