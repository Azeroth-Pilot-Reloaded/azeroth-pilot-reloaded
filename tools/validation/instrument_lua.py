"""Generate/check source-level diagnostics for every APR-owned Lua function.

No runtime debug hooks or global API monkey-patching. Local functions, recursive
functions and anonymous callbacks keep their lexical bindings. Run --write after
editing Lua; --check is enforced by the regression suite. Generated additions are
stripped before regenerating, so line identifiers remain stable and edits remain
ordinary Lua. Embedded libraries are a deliberate boundary: reusable owned library internals
remain independent of APRInstrumentation; their APR call sites are instrumented.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXCLUDED = {
    "APR-Core/core/Diagnostics.lua": "diagnostic recorder (recursion guard)",
    "APR-Core/core/DiagnosticManifest.lua": "generated coverage inventory",
    "APR-Core/core/Performance.lua": "performance recorder (recursion guard)",
    "APR-Core/core/PerformanceScopes.lua": "diagnostic lifecycle (recursion guard)",
    "APR-Core/core/ResourceMonitor.lua": "resource sampler (observer overhead)",
    "APR-Core/core/ErrorLog.lua": "error-handler safety",
    "APR-Core/core/DiagnosticReport.lua": "diagnostic formatting (recursion guard)",
}
HELPERS = {"APR:GetSettingsProfile", "APR:ShouldLogDebug", "APR:Debug", "APR:DebugEvent",
           "APR:PrintZoneDebug", "APR:FormatDebugTable", "APR:TableToDebugString"}
BASE_HEADER = ('-- Diagnostic wrappers generated by tools/validation/instrument_lua.py; edit bodies normally.\n'
          'local APRTrace = APRInstrumentation and APRInstrumentation.Wrap or function(_, fn) return fn end\n'
          'local APRYield = APRInstrumentation and APRInstrumentation.Yield or coroutine.yield\n'
          'local APRResume = APRInstrumentation and APRInstrumentation.Resume or coroutine.resume\n')
HEADER = BASE_HEADER + 'local APRPCall = APRInstrumentation and APRInstrumentation.PCall or pcall\n'
MARKER = re.compile(r'--\[\[APR_DIAG\]\].*?--\[\[/APR_DIAG\]\]', re.S)
TOKEN = re.compile(r'''--\[(=*)\[.*?\]\1\]|--[^\n]*|\[(=*)\[.*?\]\2\]|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|[A-Za-z_]\w*|\S''', re.S)


def clean(source):
    return MARKER.sub('', source.removeprefix(HEADER).removeprefix(BASE_HEADER))


def tokens(source):
    return [m for m in TOKEN.finditer(source) if not m.group().startswith('--')]


def functions(source):
    stream, stack, found = tokens(source), [], []
    for i, token in enumerate(stream):
        word = token.group()
        if word == 'function':
            j = i + 1
            while stream[j].group() != '(':
                j += 1
            name = ''.join(t.group() for t in stream[i + 1:j])
            stack.append(('function', (token, name)))
        elif word in ('if', 'repeat'):
            stack.append((word, None))
        elif word in ('for', 'while'):
            stack.append(('loop_pending', None))
        elif word == 'do':
            if stack and stack[-1][0] == 'loop_pending':
                stack[-1] = ('loop', None)
            else:
                stack.append(('do', None))
        elif word in ('end', 'until'):
            if not stack:
                raise ValueError(f'Unmatched {word} at {token.start()}')
            kind, data = stack.pop()
            if word == 'until' and kind != 'repeat':
                raise ValueError('Unmatched repeat/until')
            if kind == 'function':
                start, name = data
                found.append((start.start(), token.end(), name))
    if stack:
        raise ValueError('Unclosed Lua blocks')
    return sorted(found)


def generated(text):
    return '--[[APR_DIAG]]' + text + '--[[/APR_DIAG]]'


def instrument(source, path):
    source = clean(source)
    edits, inventory, skipped = [], [], []
    # Helper bodies (including nested local functions) must not profile logging.
    spans = functions(source)
    excluded = [(a, b) for a, b, name in spans if name in HELPERS]
    for ordinal, (start, finish, name) in enumerate(spans, 1):
        if any(a <= start < b for a, b in excluded):
            skipped.append(name or 'callback')
            continue
        line = source.count('\n', 0, start) + HEADER.count('\n') + 1
        label = name or 'callback'
        identifier = f'{path}:{line}:{label}#{ordinal}'
        inventory.append(identifier)
        if name:
            binding = name.replace(':', '.')
            edits.append((finish, generated(f'; {binding} = APRTrace("{identifier}", {binding})')))
        else:
            edits.extend(((start, generated(f'APRTrace("{identifier}", ')), (finish, generated(')'))))
    # Explicit APR call sites only: never change the global coroutine library.
    stream = tokens(source)
    for i, token in enumerate(stream[:-1]):
        if token.group() == 'pcall' and stream[i + 1].group() == '(' and (i == 0 or stream[i - 1].group() not in ('.', ':', 'function')):
            edits.extend(((token.start(), generated('APRPCall--[=[')), (token.end(), generated(']=]'))))
    for i in range(len(stream) - 2):
        if stream[i].group() == 'coroutine' and stream[i + 1].group() == '.' and stream[i + 2].group() in ('yield', 'resume'):
            start, end = stream[i].start(), stream[i + 2].end()
            alias = 'APRYield' if stream[i + 2].group() == 'yield' else 'APRResume'
            # Keep original tokens inside a comment so clean() restores them.
            edits.extend(((start, generated(alias + '--[=[')), (end, generated(']=]'))))
    for offset, addition in sorted(edits, reverse=True):
        source = source[:offset] + addition + source[offset:]
    return (HEADER + source if inventory else source), inventory, skipped


def run(write=False):
    changed, coverage = [], []
    sources = list(ROOT.joinpath('APR-Core').rglob('*.lua')) + list(ROOT.joinpath('Routes').rglob('*.lua'))
    for path in sorted(sources):
        relative = path.relative_to(ROOT).as_posix()
        if 'libs' in path.parts or 'locales' in path.parts or relative in EXCLUDED:
            continue
        source = path.read_text(encoding='utf-8-sig')
        result, names, skipped = instrument(source, relative)
        if names or skipped:
            coverage.append((relative, len(names), len(skipped)))
        if result != source:
            changed.append(relative)
            if write:
                path.write_text(result, encoding='utf-8', newline='\n')
    manifest = '-- Generated by tools/validation/instrument_lua.py. Counts are static function definitions.\n'
    manifest += 'APRInstrumentation.coverage = {\n'
    for path, count, skipped in coverage:
        manifest += f'    ["{path}"] = {{instrumented = {count}, diagnosticHelpers = {skipped}}},\n'
    manifest += '}\nAPRInstrumentation.excluded = {\n'
    for path, reason in sorted(EXCLUDED.items()):
        manifest += f'    ["{path}"] = "{reason}",\n'
    manifest += '    ["APR-Core/libs/LibAPRNavigation-1.0/**"] = "owned reusable library; independent of APRInstrumentation, covered by isolated library tests",\n'
    manifest += '    ["APR-Core/libs/**"] = "embedded library boundary; APR call sites are instrumented",\n}\n'
    manifest += ('APRInstrumentation.observers = {\n'
                 '    ["APR-Core/ui/panels/Performance*.lua"] = "viewer root timings only; nested diagnostic drawing is suppressed",\n}\n')
    destination = ROOT / 'APR-Core/core/DiagnosticManifest.lua'
    if not destination.exists() or destination.read_text(encoding='utf-8') != manifest:
        changed.append(destination.relative_to(ROOT).as_posix())
        if write:
            destination.write_text(manifest, encoding='utf-8', newline='\n')
    return changed, coverage


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changes, coverage = run(args.write)
    print(f'{sum(count for _, count, _ in coverage)} function definitions across {len(coverage)} files')
    if changes and not args.write:
        print('Run python tools/validation/instrument_lua.py --write:\n' + '\n'.join(changes))
        raise SystemExit(1)
